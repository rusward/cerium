"""C99 code generation for Hydrogen."""

from . import nodes
from .checker import INT
from .runtime import RUNTIME_SOURCE

C_TYPES = {
    "int": "int64_t",
    "double": "double",
    "bool": "bool",
    "string": "const char *",
}

PRINT_HELPERS = {
    "int": "hy_print_int",
    "double": "hy_print_double",
    "bool": "hy_print_bool",
    "string": "hy_print_string",
}

INPUT_HELPERS = {
    "input": "hy_input_string",
    "inputInt": "hy_input_int",
    "inputDouble": "hy_input_double",
    "inputBool": "hy_input_bool",
}


def escape_c_string(value: str) -> str:
    chunks = ['"']
    for ch in value:
        if ch == "\\":
            chunks.append("\\\\")
        elif ch == '"':
            chunks.append('\\"')
        elif ch == "\n":
            chunks.append("\\n")
        elif ch == "\t":
            chunks.append("\\t")
        elif ch == "\r":
            chunks.append("\\r")
        elif ord(ch) < 32 or ord(ch) == 127:
            chunks.append("\\%03o" % ord(ch))
        else:
            chunks.append(ch)
    chunks.append('"')
    return "".join(chunks)


def escape_c_filename(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def format_float(value: float) -> str:
    text = repr(value)
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


class CCodegen:
    def __init__(self, program: nodes.Program, types: dict, filename: str):
        self.program = program
        self.types = types
        self.filename = filename
        self.structs = {}
        self.lines = []

    def generate(self) -> str:
        self.collect_structs()

        self.lines.append("/* Generated by hydrogenc. Do not edit. */")
        self.lines.append("#include <stdbool.h>")
        self.lines.append("#include <stdint.h>")
        self.lines.append("#include <inttypes.h>")
        self.lines.append("#include <stdio.h>")
        self.lines.append("#include <stdlib.h>")
        self.lines.append("#include <string.h>")
        self.lines.append("#include <errno.h>")
        self.lines.append("")
        self.lines.append(f"#define HY_FILE {escape_c_string(self.filename)}")
        self.lines.append(RUNTIME_SOURCE)

        self.emit_structs()
        self.emit_prototypes()

        for statement in self.program.statements:
            if isinstance(statement, nodes.FuncDecl):
                self.emit_function(statement)

        self.lines.append("int main(void) {")
        for statement in self.program.statements:
            if isinstance(statement, (nodes.FuncDecl, nodes.StructDecl)):
                continue
            self.emit_statement(statement, 1)
        self.lines.append("    return 0;")
        self.lines.append("}")
        return "\n".join(self.lines) + "\n"

    # -- declarations ------------------------------------------------------

    def collect_structs(self) -> None:
        for statement in self.program.statements:
            if not isinstance(statement, nodes.StructDecl):
                continue
            if statement.name in self.structs:
                continue
            self.structs[statement.name] = [
                (field.name, field.type_name) for field in statement.fields
            ]

    def emit_structs(self) -> None:
        for name, fields in self.structs.items():
            self.lines.append(f"typedef struct hy_struct_{name} {{")
            for field, field_type in fields:
                self.lines.append(
                    f"    {self.c_type(field_type)} hy_f_{field};"
                )
            self.lines.append(f"}} hy_struct_{name};")
            self.lines.append("")

    def emit_prototypes(self) -> None:
        for statement in self.program.statements:
            if not isinstance(statement, nodes.FuncDecl):
                continue
            params = self.param_list(statement.params)
            self.lines.append(
                f"static {self.c_type(statement.return_type)} "
                f"hy_fn_{statement.name}({params});"
            )
        self.lines.append("")

    def emit_function(self, function: nodes.FuncDecl) -> None:
        params = self.param_list(function.params)
        self.emit_line_directive(function)
        self.lines.append(
            f"static {self.c_type(function.return_type)} "
            f"hy_fn_{function.name}({params}) {{"
        )
        for statement in function.body:
            self.emit_statement(statement, 1)
        self.lines.append("}")
        self.lines.append("")

    def param_list(self, params) -> str:
        if not params:
            return "void"
        return ", ".join(
            f"{self.c_type(param.type_name)} hy_v_{param.name}"
            for param in params
        )

    def c_type(self, type_name: str) -> str:
        if type_name == "void":
            return "void"
        if type_name in C_TYPES:
            return C_TYPES[type_name]
        return f"hy_struct_{type_name}"

    # -- emission helpers --------------------------------------------------

    def emit(self, text: str, indent: int = 0) -> None:
        self.lines.append("    " * indent + text)

    def emit_line_directive(self, node) -> None:
        self.lines.append(
            f'#line {node.line} "{escape_c_filename(self.filename)}"'
        )

    # -- statements --------------------------------------------------------

    def emit_statement(self, statement, indent: int) -> None:
        if isinstance(statement, nodes.VarDecl):
            self.emit_line_directive(statement)
            self.emit(self.declaration_text(statement) + ";", indent)

        elif isinstance(statement, nodes.Assign):
            self.emit_line_directive(statement)
            self.emit(self.assignment_text(statement) + ";", indent)

        elif isinstance(statement, nodes.ExprStmt):
            self.emit_call_statement(statement.expr, indent)

        elif isinstance(statement, nodes.If):
            self.emit_if(statement, indent)

        elif isinstance(statement, nodes.While):
            self.emit_line_directive(statement)
            self.emit(f"while ({self.expression(statement.cond)}) {{", indent)
            for inner in statement.body:
                self.emit_statement(inner, indent + 1)
            self.emit("}", indent)

        elif isinstance(statement, nodes.For):
            self.emit_line_directive(statement)
            self.emit(
                f"for ({self.for_init_text(statement.init)}; "
                f"{self.expression(statement.cond)}; "
                f"{self.assignment_text(statement.update)}) {{",
                indent,
            )
            for inner in statement.body:
                self.emit_statement(inner, indent + 1)
            self.emit("}", indent)

        elif isinstance(statement, nodes.Loop):
            self.emit_line_directive(statement)
            self.emit("while (true) {", indent)
            for inner in statement.body:
                self.emit_statement(inner, indent + 1)
            self.emit("}", indent)

        elif isinstance(statement, nodes.Break):
            self.emit("break;", indent)

        elif isinstance(statement, nodes.Continue):
            self.emit("continue;", indent)

        elif isinstance(statement, nodes.Return):
            if statement.expr is None:
                self.emit("return;", indent)
            else:
                self.emit(f"return {self.expression(statement.expr)};", indent)

    def declaration_text(self, declaration: nodes.VarDecl) -> str:
        return (
            f"{self.c_type(declaration.type_name)} "
            f"hy_v_{declaration.name} = "
            f"{self.expression(declaration.expr)}"
        )

    def assignment_text(self, assignment: nodes.Assign) -> str:
        return (
            f"{self.expression(assignment.target)} = "
            f"{self.expression(assignment.expr)}"
        )

    def for_init_text(self, init) -> str:
        if isinstance(init, nodes.VarDecl):
            return self.declaration_text(init)
        return self.assignment_text(init)

    def emit_call_statement(self, call, indent: int) -> None:
        if call.name == "log":
            for index, argument in enumerate(call.args):
                if index:
                    self.emit("putchar(32);", indent)
                argument_type = self.types[id(argument)]
                helper = PRINT_HELPERS[argument_type]
                self.emit(f"{helper}({self.expression(argument)});", indent)
            self.emit("putchar(10);", indent)
            return

        self.emit(self.expression(call) + ";", indent)

    def emit_if(self, statement: nodes.If, indent: int) -> None:
        self.emit_line_directive(statement)
        for index, (condition, body) in enumerate(statement.branches):
            keyword = "if" if index == 0 else "else if"
            self.emit(f"{keyword} ({self.expression(condition)}) {{", indent)
            for inner in body:
                self.emit_statement(inner, indent + 1)
            self.emit("}", indent)
        if statement.else_body is not None:
            self.emit("else {", indent)
            for inner in statement.else_body:
                self.emit_statement(inner, indent + 1)
            self.emit("}", indent)

    # -- expressions -------------------------------------------------------

    def expression(self, expr) -> str:
        if isinstance(expr, nodes.IntLit):
            return f"INT64_C({expr.value})"

        if isinstance(expr, nodes.FloatLit):
            return format_float(expr.value)

        if isinstance(expr, nodes.StringLit):
            return escape_c_string(expr.value)

        if isinstance(expr, nodes.BoolLit):
            return "true" if expr.value else "false"

        if isinstance(expr, nodes.Var):
            return f"hy_v_{expr.name}"

        if isinstance(expr, nodes.FieldAccess):
            return (
                f"({self.expression(expr.base)}).hy_f_{expr.field}"
            )

        if isinstance(expr, nodes.StructLit):
            return self.struct_literal(expr)

        if isinstance(expr, nodes.Call):
            if expr.name in INPUT_HELPERS:
                prompt = (
                    self.expression(expr.args[0]) if expr.args else "NULL"
                )
                return (
                    f"{INPUT_HELPERS[expr.name]}({prompt}, {expr.line})"
                )
            args = ", ".join(self.expression(argument) for argument in expr.args)
            return f"hy_fn_{expr.name}({args})"

        if isinstance(expr, nodes.Unary):
            operand = self.expression(expr.operand)
            if expr.op == "-":
                if self.types[id(expr)] == INT:
                    return f"hy_neg_int({operand})"
                return f"(-{operand})"
            return f"(!{operand})"

        if isinstance(expr, nodes.Binary):
            return self.binary_expression(expr)

        raise AssertionError(f"unexpected expression node: {expr!r}")

    def struct_literal(self, literal: nodes.StructLit) -> str:
        if literal.fields:
            fields = ", ".join(
                f".hy_f_{field.name} = {self.expression(field.expr)}"
                for field in literal.fields
            )
            return f"(hy_struct_{literal.type_name}){{ {fields} }}"
        return f"(hy_struct_{literal.type_name}){{0}}"

    def binary_expression(self, expr: nodes.Binary) -> str:
        left = self.expression(expr.left)
        right = self.expression(expr.right)
        op = expr.op
        left_type = self.types[id(expr.left)]

        if op == "+":
            if left_type == "string":
                return f"hy_str_concat({left}, {right})"
            if left_type == INT:
                return f"hy_add_int({left}, {right})"
            return f"({left} + {right})"

        if op == "-":
            if left_type == INT:
                return f"hy_sub_int({left}, {right})"
            return f"({left} - {right})"

        if op == "*":
            if left_type == INT:
                return f"hy_mul_int({left}, {right})"
            return f"({left} * {right})"

        if op == "/":
            if left_type == INT:
                return f"hy_div_int({left}, {right}, {expr.line})"
            return f"({left} / {right})"

        if op == "%":
            return f"hy_mod_int({left}, {right}, {expr.line})"

        if op in ("==", "!="):
            if left_type == "string":
                comparison = f"hy_str_eq({left}, {right})"
                return comparison if op == "==" else f"(!{comparison})"
            return f"({left} {op} {right})"

        return f"({left} {op} {right})"
